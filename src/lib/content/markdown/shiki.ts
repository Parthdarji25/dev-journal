import { bundledLanguages, createHighlighter, type BundledLanguage, type Highlighter } from 'shiki';
import { classList, isElement, toText, walk, type HastElement, type UnistNode } from './tree';

export const SHIKI_THEMES = { light: 'github-light-default', dark: 'github-dark-default' } as const;

let highlighterPromise: Promise<Highlighter> | undefined;

export function getHighlighter(): Promise<Highlighter> {
  highlighterPromise ??= createHighlighter({
    themes: [SHIKI_THEMES.light, SHIKI_THEMES.dark],
    langs: [],
  });
  return highlighterPromise;
}

function resolveLanguage(lang: string): BundledLanguage | undefined {
  const key = lang.toLowerCase();
  return key in bundledLanguages ? (key as BundledLanguage) : undefined;
}

/*
 * Shiki colours tokens with inline style attributes. A strict CSP forbids
 * those, so each colour becomes a class (`sl-<hex>` for light, `sd-<hex>` for
 * dark) backed by the generated src/styles/shiki.css.
 */
const STYLE_FLAGS: Record<string, string> = {
  'font-style:italic': 'i',
  'font-weight:bold': 'b',
  'text-decoration:underline': 'u',
};

export function styleToClasses(style: string): string[] {
  const classes: string[] = [];
  for (const decl of style.split(';')) {
    const match = /^--shiki-(light|dark)(?:-(font-style|font-weight|text-decoration))?:(.+)$/.exec(
      decl.trim(),
    );
    if (!match) continue;
    const prefix = match[1] === 'light' ? 'sl' : 'sd';
    const prop = match[2];
    const value = (match[3] ?? '').trim().toLowerCase();
    if (!prop) {
      if (/^#[0-9a-f]{3,8}$/.test(value)) classes.push(`${prefix}-${value.slice(1)}`);
    } else {
      const flag = STYLE_FLAGS[`${prop}:${value}`];
      if (flag) classes.push(`${prefix}-${flag}`);
    }
  }
  return classes;
}

/** Async rehype transformer: highlights every `pre > code.language-*` block. */
export function rehypeShiki() {
  return async (tree: UnistNode) => {
    const blocks: { pre: HastElement; lang: BundledLanguage; code: string; label: string }[] = [];
    walk(tree, (node) => {
      if (!isElement(node, 'pre')) return;
      const code = node.children.find((c) => isElement(c, 'code')) as HastElement | undefined;
      if (!code) return 'skip';
      const langClass = classList(code).find((c) => c.startsWith('language-'));
      const label = langClass?.slice('language-'.length) ?? '';
      node.properties.dataLanguage = label || 'text';
      node.properties.tabIndex = 0;
      const lang = label ? resolveLanguage(label) : undefined;
      if (lang) blocks.push({ pre: node, lang, code: toText(code).replace(/\n$/, ''), label });
      return 'skip';
    });
    if (blocks.length === 0) return;

    const highlighter = await getHighlighter();
    for (const { pre, lang, code, label } of blocks) {
      if (!highlighter.getLoadedLanguages().includes(lang)) await highlighter.loadLanguage(lang);
      const root = highlighter.codeToHast(code, {
        lang,
        themes: SHIKI_THEMES,
        defaultColor: false,
      }) as unknown as UnistNode;
      const highlighted = root.children?.find((c) => isElement(c, 'pre')) as
        HastElement | undefined;
      if (!highlighted) continue;
      walk(highlighted as UnistNode, (node) => {
        if (!isElement(node)) return;
        const style = node.properties.style;
        delete node.properties.style;
        if (node.tagName === 'span' && typeof style === 'string') {
          const extra = styleToClasses(style);
          if (extra.length) node.properties.className = [...classList(node), ...extra];
          delete node.properties.class;
        }
      });
      pre.properties = { className: ['shiki'], dataLanguage: label, tabIndex: 0 };
      pre.children = highlighted.children;
    }
  };
}

/** The stylesheet behind `styleToClasses`, covering every colour both themes can emit. */
export async function shikiCss(): Promise<string> {
  const lines = ['/* Generated by scripts/gen-shiki-css.ts. Do not edit. */'];
  for (const [mode, prefix] of [
    ['light', 'sl'],
    ['dark', 'sd'],
  ] as const) {
    const scope = mode === 'light' ? ':root:not(.dark)' : '.dark';
    for (const colour of (await themeColours(mode)).sort()) {
      lines.push(`${scope} .${prefix}-${colour.slice(1)} { color: ${colour}; }`);
    }
    lines.push(`${scope} .${prefix}-i { font-style: italic; }`);
    lines.push(`${scope} .${prefix}-b { font-weight: 600; }`);
    lines.push(`${scope} .${prefix}-u { text-decoration: underline; }`);
  }
  return `${lines.join('\n')}\n`;
}

/**
 * Token colours we style. Scopes that pair a foreground with their own
 * background (diff markers, carriage returns) are skipped: we never render
 * token backgrounds, so those tokens fall back to the normal code colour.
 */
export async function themeColours(mode: 'light' | 'dark'): Promise<string[]> {
  const theme = (await getHighlighter()).getTheme(SHIKI_THEMES[mode]);
  const set = new Set<string>(theme.fg ? [theme.fg.toLowerCase()] : []);
  for (const { scope, settings } of theme.settings) {
    if (settings.foreground && !(scope && settings.background))
      set.add(settings.foreground.toLowerCase());
  }
  return [...set];
}
